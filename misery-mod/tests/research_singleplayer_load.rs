/// What the game intends to load right now, before anything is
/// clicked.
///
/// If the slot name is empty at the main menu, then the menu sets
/// it when a row is clicked, and auto-load has to set it too
/// rather than read it back. That is the difference between
/// loading the player's save and generating a new world.
///
/// Read-only: both calls are getters.
#[test]
fn what_the_game_intends_to_load() {
    let Some(api) = api_or_skip() else { return };
    let live = modforge::client::walk_class_chain_instances(&api, "BP_SGKGameInstance_C", 4);
    let Some(gi) = live.iter().find(|w| w.full_name.contains("/Engine/Transient")) else {
        println!("no live game instance");
        return;
    };
    println!("game instance: {}", gi.full_name);

    let flag = api.op(
        "call",
        json!({
            "class": "BP_SGKGameInstance_C",
            "function": "SGK GetLoadSaveGame",
            "instance_selector": gi.addr_selector,
            "parms_hex": "00",
        }),
    );
    common::show("SGK GetLoadSaveGame", &flag);

    let name = api.op(
        "call",
        json!({
            "class": "BP_SGKGameInstance_C",
            "function": "SGK GetSaveGameSlotName",
            "instance_selector": gi.addr_selector,
            "parms_hex": "0".repeat(32),
        }),
    );
    common::show("SGK GetSaveGameSlotName", &name);
    if let Some(hex) = name.result["parms_hex_after"].as_str() {
        println!("slot name: {:?}", read_fstring(&api, hex));
    }
}

/// Decode an `FString` parm block: `{ TCHAR* Data; int32 Num;
/// int32 Max; }`, UTF-16 characters.
fn read_fstring(api: &common::Api, parms_hex: &str) -> String {
    let bytes = hex_to_bytes(parms_hex);
    if bytes.len() < 16 {
        return String::new();
    }
    let ptr = u64::from_le_bytes(bytes[0..8].try_into().unwrap());
    let num = i32::from_le_bytes(bytes[8..12].try_into().unwrap());
    if ptr == 0 || num <= 0 {
        return String::new();
    }
    let r = api.op(
        "read_bytes",
        json!({
            "instance_selector": format!("addr:0x{ptr:X}"),
            "offset": 0,
            "length": (num as usize) * 2,
        }),
    );
    if !r.ok {
        return format!("<read_bytes failed: {:?}>", r.error);
    }
    let raw = hex_to_bytes(r.result["bytes_hex"].as_str().unwrap_or(""));
    let units: Vec<u16> = raw
        .chunks_exact(2)
        .map(|c| u16::from_le_bytes([c[0], c[1]]))
        .take_while(|c| *c != 0)
        .collect();
    String::from_utf16_lossy(&units)
}

fn hex_to_bytes(s: &str) -> Vec<u8> {
    (0..s.len() / 2)
        .filter_map(|i| u8::from_str_radix(&s[i * 2..i * 2 + 2], 16).ok())
        .collect()
}
