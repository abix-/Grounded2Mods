//! What does the game do when a player clicks Singleplayer, Load
//! Game, then a save?
//!
//! Auto-load currently calls `LoadLevel` on the object named
//! `BP_HostLoadGameServer`. That is the host-a-server path: every
//! launch came up in a FRESH world, with a different world number
//! each time (5760, 244, 10776, 15820), rather than the save.
//! So `LoadLevel` there is the wrong call, or something has to be
//! set before it that the menu sets and we do not.
//!
//! Same method that solved the playtest notice (research.md
//! 26.5): find the widget the player's click actually reaches,
//! read its live function list, and look for the handler that
//! click runs. A Blueprint button handler is named after the
//! button it belongs to, so the name identifies it.
//!
//! EVERYTHING HERE IS READ-ONLY. The save rows carry a delete
//! button as well as a load button, and both are named only by
//! number (`Button_284`, `Button_372`), so nothing is called
//! until the printout says which is which.
//!
//! Run at the MAIN MENU, before loading anything:
//!
//! ```text
//! MISERY_DEBUG_PORT=17176 cargo test -p misery-mod --test research_singleplayer_load -- --test-threads=1 --nocapture
//! ```

mod common;
use common::api_or_skip;
use serde_json::json;

/// Parts of a class name worth looking for on the main menu.
/// `walk_class_chain` matches a fragment, so this finds classes
/// nobody has named yet, including whatever sits behind the
/// Singleplayer button.
const NEEDLES: &[&str] = &[
    "SinglePlayer",
    "Singleplayer",
    "LoadSave",
    "SaveGame",
    "LoadGame",
    "Host",
    "MainMenu",
];

/// Every live object on the main menu whose class name contains
/// one of the fragments above.
///
/// The point is the object NAMES. `BP_HostLoadGameServer` and
/// `BP_HostNewGameServer` are both instances of the one class
/// `BP_HostNewGameServer_C`, so the class alone does not say
/// which is which, and there may be a singleplayer counterpart
/// hiding the same way.
#[test]
fn live_menu_objects() {
    let Some(api) = api_or_skip() else { return };
    for needle in NEEDLES {
        let r = api.op("walk_class_chain", json!({ "needle": needle, "max": 64 }));
        if !r.ok {
            println!("\n=== {needle}: FAILED {:?}", r.error);
            continue;
        }
        let all = r.result["instances"].as_array().cloned().unwrap_or_default();
        // Templates inside a /Game/... package are not real
        // objects; calling one succeeds and does nothing.
        let live: Vec<&serde_json::Value> = all
            .iter()
            .filter(|i| {
                i["full_name"]
                    .as_str()
                    .map(|n| n.contains("/Engine/Transient"))
                    .unwrap_or(false)
            })
            .collect();
        println!(
            "\n=== {needle}: {} total, {} live",
            r.result["total"], live.len()
        );
        for i in live {
            println!("  {}", i["full_name"].as_str().unwrap_or("?"));
            println!("    {}", i["addr_selector"].as_str().unwrap_or("?"));
        }
    }
}

/// Classes on the load path. The first four are the widgets the
/// player clicks through; the last two are where the choice is
/// stored and acted on.
const LOAD_PATH: &[&str] = &[
    "BP_MainMenu_C",
    "BP_SingleplayerMenu_C",
    "BP_LoadGameMenu_C",
    "BP_LoadGameMenuPanel_C",
    "BP_HostNewGameServer_C",
    "BP_SGKGameInstance_C",
];

/// Words that mark a function worth reading twice.
const INTERESTING: &[&str] = &[
    "Load", "Save", "Slot", "Open", "Level", "Travel", "Start",
    "Single", "Host", "Server", "Button", "BndEvt", "Clicked",
];

/// Every function each widget on the load path can be told to
/// run, with the interesting ones marked.
///
/// A button handler generated by a Blueprint carries the button's
/// own name, e.g.
/// `BndEvt__..._Button_284_..._OnButtonClickedEvent__DelegateSignature`.
/// That is what the click runs, and it is what to call.
#[test]
fn load_path_functions() {
    let Some(api) = api_or_skip() else { return };
    for class in LOAD_PATH {
        let r = api.op("class_functions", json!({ "class": class }));
        if !r.ok {
            println!("\n=== {class}: FAILED {:?}", r.error);
            continue;
        }
        let fns = r.result["functions"].as_array().cloned().unwrap_or_default();
        println!("\n=== {class} ({} functions)", fns.len());
        println!("    {}", r.result["full_name"].as_str().unwrap_or("?"));
        for f in &fns {
            let name = f["name"].as_str().unwrap_or("?");
            let mark = if INTERESTING.iter().any(|w| name.contains(w)) { ">>" } else { "  " };
            println!(
                "{mark} {name:<70} parms={} bytes={}",
                f["num_parms"], f["parms_size"]
            );
        }
    }
}

/// What each save row holds and what its buttons are called.
///
/// One row per save. Each has two buttons named only by number,
/// one to load and one to delete, so the field list is the only
/// thing that ties a number to a save. Read-only: nothing is
/// called on a row here.
#[test]
fn save_row_contents() {
    let Some(api) = api_or_skip() else { return };
    for class in ["BP_LoadGameMenu_C", "BP_LoadGameMenuPanel_C"] {
        let live = modforge::client::walk_class_chain_instances(&api, class, 16);
        println!("\n=== {class}: {} live instance(s)", live.len());
        for w in &live {
            println!("\n-- {}", w.full_name);
            let r = api.op("inspect_address", json!({"addr": format!("0x{:X}", w.addr)}));
            if r.ok {
                println!("{}", serde_json::to_string_pretty(&r.result).unwrap_or_default());
            } else {
                println!("   inspect failed: {:?}", r.error);
            }
        }
    }
}

